/**
 * stripMarkdownForCopy / stripMarkdownForSpeech 的共用剥离原语。
 * 两者对围栏代码块的**策略**不同（复制保留内容 / 朗读整体移除），但「闭围栏识别」与
 * 「散文级 markdown 语法剥离」必须同口径——曾各自手写复本导致口径漂移（闭围栏是否
 * 允许 info string 两处答案不同），故收敛到这一处，改动自动同时生效。
 */

// 闭合围栏代码块：开围栏行（允许 info string）+ 内容 + 闭围栏行 + 可选换行。
// 闭围栏行只允许同类围栏字符延长 + 尾随空白（CommonMark 闭围栏不得带 info string，
// 长度可长于开围栏）：若允许任意尾文本，围栏内容里出现的 "```python" 行（模型演示
// markdown 语法时常见）会被误当闭围栏提前切分，其后代码泄入散文剥离。
// 捕获组供 stripMarkdownForCopy 以 split 取 [文本, 围栏符, 代码] 三元组；replace 消费方忽略分组。
export const CLOSED_FENCE_RE =
  /^[ \t]{0,3}(`{3,}|~{3,})[^\n]*\n([\s\S]*?)^[ \t]{0,3}\1[`~]*[ \t]*$\n?/gm;

/**
 * 散文级 markdown 语法剥离：图片/链接留文字、强调/删除线去符号、标题/引用/列表/水平线去标记。
 * 调用方须先把代码内容摘出（复制场景占位保护 / 朗读场景移除或去反引号），本函数不感知代码区。
 */
export const stripInlineProse = (text: string): string =>
  text
    // 图片 ![alt](url) → alt（须先于链接处理）
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 链接 [text](url) → text
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 加粗 **x** → x：要求内容首尾非空白，避免把两侧带空格的 ** 当成强调符号误吃
    .replace(/\*\*(\S(?:.*?\S)?)\*\*/g, '$1')
    // 加粗 __x__ → x：额外要求左右不紧贴字母数字/下划线，避免误吃双下划线标识符（如 __init__）
    .replace(/(?<![\w_])__(\S(?:.*?\S)?)__(?![\w_])/g, '$1')
    // 斜体 *x* → x：要求内容首尾非空白，避免把两侧带空格的乘号当成强调符号（如 "1 * 2 * 3"）
    .replace(/\*([^\s*](?:.*?[^\s*])?)\*/g, '$1')
    // 斜体 _x_ → x：额外要求左右不紧贴字母数字/下划线，避免误吃 snake_case 标识符（如 my_var_name）
    .replace(/(?<![\w_])_([^\s_](?:.*?[^\s_])?)_(?![\w_])/g, '$1')
    // 删除线 ~~x~~ → x
    .replace(/~~(.*?)~~/g, '$1')
    // 标题井号（行首 # ~ ###### ）
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    // 引用符号（行首 > ）
    .replace(/^\s{0,3}>\s?/gm, '')
    // 无序列表符号（行首 - * + ）
    .replace(/^\s{0,3}[-*+]\s+/gm, '')
    // 有序列表序号（行首 1. ）
    .replace(/^\s{0,3}\d+\.\s+/gm, '')
    // 水平分割线（--- *** ___）
    .replace(/^\s{0,3}([-*_])(?:\s*\1){2,}\s*$/gm, '');
