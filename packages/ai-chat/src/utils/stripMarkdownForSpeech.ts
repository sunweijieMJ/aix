/**
 * 将 markdown 文本轻量剥离为适合朗读的纯文本：
 * 去围栏代码块、标题井号、强调符、行内代码反引号、链接/图片保留文字、列表/引用符号、水平线，收敛空行。
 * 仅做朗读体验优化，非完备 markdown 解析。text 块承载含围栏的 markdown 源，故先整体移除围栏
 * 代码块（含流式中断的未闭合围栏），避免整段代码被逐字朗读；思维链 / 来源块属独立块类型，天然不进此文本。
 */
export const stripMarkdownForSpeech = (md: string): string =>
  md
    // 围栏代码块 ```lang ... ``` / ~~~ ... ~~~（含语言标注行）→ 整体移除（须先于行内代码处理）
    .replace(/^[ \t]{0,3}(`{3,}|~{3,})[^\n]*\n[\s\S]*?^[ \t]{0,3}\1[^\n]*$\n?/gm, '')
    // 未闭合围栏（流式中断）→ 从围栏起剥到文本末尾
    .replace(/^[ \t]{0,3}(`{3,}|~{3,})[\s\S]*$/gm, '')
    // 图片 ![alt](url) → alt（须先于链接处理）
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 链接 [text](url) → text
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 行内代码 `code` → code（限单行内配对，不跨行撕裂围栏残片）
    .replace(/`([^`\n]+)`/g, '$1')
    // 强调符四条与 stripMarkdownForCopy 的 stripProse 保持同一口径，改一处须同步另一处：
    // 无边界约束的写法（如 /(\*|_)(.*?)\1/）会把散文里的标识符和乘号当成强调符吃掉，
    // 朗读出来就是错的——"user_id 和 order_id" 念成 "userid 和 orderid"、"2 * 3 * 4" 念成 "2 3 4"。
    // 加粗 **x** → x：要求内容首尾非空白，避免把两侧带空格的 ** 当成强调符号误吃
    .replace(/\*\*(\S(?:.*?\S)?)\*\*/g, '$1')
    // 加粗 __x__ → x：额外要求左右不紧贴字母数字/下划线，避免误吃双下划线标识符（如 __init__）
    .replace(/(?<![\w_])__(\S(?:.*?\S)?)__(?![\w_])/g, '$1')
    // 斜体 *x* → x：要求内容首尾非空白，避免把两侧带空格的乘号当成强调符号（如 "1 * 2 * 3"）
    .replace(/\*([^\s*](?:.*?[^\s*])?)\*/g, '$1')
    // 斜体 _x_ → x：额外要求左右不紧贴字母数字/下划线，避免误吃 snake_case 标识符（如 my_var_name）
    .replace(/(?<![\w_])_([^\s_](?:.*?[^\s_])?)_(?![\w_])/g, '$1')
    // 删除线 ~~x~~ → x
    .replace(/~~(.*?)~~/g, '$1')
    // 标题井号（行首 # ~ ###### ）
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    // 引用符号（行首 > ）
    .replace(/^\s{0,3}>\s?/gm, '')
    // 无序列表符号（行首 - * + ）
    .replace(/^\s{0,3}[-*+]\s+/gm, '')
    // 有序列表序号（行首 1. ）
    .replace(/^\s{0,3}\d+\.\s+/gm, '')
    // 水平分割线（--- *** ___）
    .replace(/^\s{0,3}([-*_])(?:\s*\1){2,}\s*$/gm, '')
    // 多余空白行收敛为至多一个空行
    .replace(/\n{3,}/g, '\n\n')
    .trim();
