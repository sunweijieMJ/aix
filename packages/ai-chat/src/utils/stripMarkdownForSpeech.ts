/**
 * 将 markdown 文本轻量剥离为适合朗读的纯文本：
 * 去标题井号、强调符、行内代码反引号、链接/图片保留文字、列表/引用符号、水平线，收敛空行。
 * 仅做朗读体验优化，非完备 markdown 解析——代码块 / 思维链 / 来源块本就不在 text 块内，天然不朗读。
 */
export const stripMarkdownForSpeech = (md: string): string =>
  md
    // 图片 ![alt](url) → alt（须先于链接处理）
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 链接 [text](url) → text
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // 行内代码 `code` → code
    .replace(/`([^`]+)`/g, '$1')
    // 加粗 **x** / __x__ → x
    .replace(/(\*\*|__)(.*?)\1/g, '$2')
    // 斜体 *x* / _x_ → x
    .replace(/(\*|_)(.*?)\1/g, '$2')
    // 删除线 ~~x~~ → x
    .replace(/~~(.*?)~~/g, '$1')
    // 标题井号（行首 # ~ ###### ）
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    // 引用符号（行首 > ）
    .replace(/^\s{0,3}>\s?/gm, '')
    // 无序列表符号（行首 - * + ）
    .replace(/^\s{0,3}[-*+]\s+/gm, '')
    // 有序列表序号（行首 1. ）
    .replace(/^\s{0,3}\d+\.\s+/gm, '')
    // 水平分割线（--- *** ___）
    .replace(/^\s{0,3}([-*_])(?:\s*\1){2,}\s*$/gm, '')
    // 多余空白行收敛为至多一个空行
    .replace(/\n{3,}/g, '\n\n')
    .trim();
